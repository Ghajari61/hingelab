// Run through vite-node: npx vite-node -c vitest.config.ts scripts/build-splash-title.ts
// Writes components/splash/title.generated.ts: the outlines of "Hinge" and "Lab" in Cinzel Bold
// (cap height 10, y up, centred on the whole word), so the splash screen extrudes real lettering
// without loading HarfBuzz or a font at start-up.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as hb from "harfbuzzjs";
import { BUNDLED_FONTS, loadFont } from "@/lib/letters/fonts";
import { unionShapes } from "@/lib/letters/polygon";
import { makeTextFn } from "@/lib/generators/text";

const info = BUNDLED_FONTS.find((f) => f.id === "cinzel")!;
const b = readFileSync(join(process.cwd(), "public/fonts", info.file));
const font = loadFont(hb, info.id, info.name, b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer);
const text = makeTextFn(hb, (id) => (id === "cinzel" ? font : null));
const t = text("HingeLab", "cinzel", 10, 0.4)!;
const r = (v: number) => Math.round(v * 100) / 100;
const word = (gs: [number, number][][][]) => unionShapes(gs.flat()).map((s) => ({
  // y up for three.js; drop near-duplicate points
  outer: thin(s.outer.map(([x, y]) => [r(x), r(-y)])),
  holes: s.holes.map((h) => thin(h.map(([x, y]) => [r(x), r(-y)]))),
}));
function thin(c: number[][]) {
  const out: number[][] = [];
  for (const p of c) { const q = out[out.length - 1]; if (!q || Math.hypot(p[0] - q[0], p[1] - q[1]) > 0.06) out.push(p); }
  return out;
}
const hinge = word(t.glyphs!.slice(0, 5) as [number, number][][][]);
const lab = word(t.glyphs!.slice(5) as [number, number][][][]);
const src = `// Generated by scripts/build-splash-title.ts from Cinzel Bold (SIL Open Font License). Do not edit.
export interface TitleShape { outer: number[][]; holes: number[][][] }
export const TITLE = { width: ${r(t.width)}, height: ${r(t.height)}, hinge: ${JSON.stringify(hinge)} as TitleShape[], lab: ${JSON.stringify(lab)} as TitleShape[] };
`;
writeFileSync(join(process.cwd(), "components/splash/title.generated.ts"), src);
console.log("title", t.width.toFixed(1), "×", t.height.toFixed(1), (src.length / 1024).toFixed(1), "kB");
