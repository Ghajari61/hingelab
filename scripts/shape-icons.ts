// Writes lib/parametric/shapeIcons.generated.ts. Usage: npm run build:shape-icons
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { allShapeIcons } from "@/lib/parametric/shapeIcons";

const icons = allShapeIcons();
const body = Object.entries(icons).map(([k, d]) => `  ${JSON.stringify(k)}: ${JSON.stringify(d)},`).join("\n");
const src = `// Generated by scripts/shape-icons.ts from the shape formulas. Do not edit.\nexport const SHAPE_ICONS: Record<string, string> = {\n${body}\n};\n`;
writeFileSync(resolve("lib/parametric/shapeIcons.generated.ts"), src);
console.log(`wrote ${Object.keys(icons).length} icons`);
